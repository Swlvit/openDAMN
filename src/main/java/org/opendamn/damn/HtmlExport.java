package org.opendamn.damn;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/** Exports a menu tree as a single web page with icon and preview image files. */
public final class HtmlExport {

    /** What to include. */
    public record Options(String title, String header1, String header2, boolean previews, boolean info1,
                          boolean info2, boolean info, boolean description, boolean tgi, int columns, int columnWidth) {}

    private HtmlExport() {}

    public static Path export(DamnMenus menus, MenuNode start, Path dir, Options o) throws IOException {
        Files.createDirectories(dir.resolve("MenuIcons"));
        if (o.previews()) Files.createDirectories(dir.resolve("MenuPreviews"));
        StringBuilder sb = new StringBuilder();
        sb.append("<!DOCTYPE html>\n<html><head><meta charset=\"utf-8\"><title>").append(esc(o.title())).append("</title>\n");
        sb.append("<style>body{font-family:sans-serif;background:#f4f7fa;margin:20px}h1{margin:0}h2{margin:2px 0 16px;"
                + "font-weight:normal;color:#456}details{margin:6px 0;background:#fff;border:1px solid #cdd;border-radius:6px;"
                + "padding:4px 10px}summary{cursor:pointer;font-weight:bold;padding:4px}.grid{display:grid;"
                + "grid-template-columns:repeat(").append(o.columns()).append(",").append(o.columnWidth())
                .append("px);gap:8px;padding:8px 0}.item{display:flex;gap:8px;border-top:1px solid #eee;padding:6px}"
                + ".item img.icon{width:44px;height:44px}.item img.preview{max-width:120px}.small{font-size:85%;color:#555}"
                + ".tgi{font-family:monospace;font-size:80%;color:#789}</style></head><body>\n");
        sb.append("<h1>").append(esc(o.header1())).append("</h1><h2>").append(esc(o.header2())).append("</h2>\n");
        sb.append("<p><button onclick=\"document.querySelectorAll('details').forEach(d=>d.open=true)\">Show all</button> "
                + "<button onclick=\"document.querySelectorAll('details').forEach(d=>d.open=false)\">Hide all</button></p>\n");
        int[] counter = {0};
        for (MenuNode n : start.descendantsAndSelf()) {
            menus.ensureLoaded(n);
            if (n.items().isEmpty()) continue;
            sb.append("<details><summary>").append(esc(n.displayPath().replace("/", " → "))).append(" (")
                    .append(n.items().size()).append(")</summary><div class=\"grid\">\n");
            for (MenuItem it : n.items()) appendItem(sb, it, dir, o, counter);
            sb.append("</div></details>\n");
        }
        sb.append("<p class=\"small\">Generated by OpenDAMN</p></body></html>\n");
        Path out = dir.resolve("DAMN_Menu_Contents.html");
        Files.writeString(out, sb.toString(), StandardCharsets.UTF_8);
        return out;
    }

    private static void appendItem(StringBuilder sb, MenuItem it, Path dir, Options o, int[] counter) throws IOException {
        String id = String.format("%05d_%08x", counter[0]++, it.exemplarInstance());
        sb.append("<div class=\"item\">");
        if (it.icon() != null) {
            Files.write(dir.resolve("MenuIcons").resolve(id + ".png"), it.icon());
            sb.append("<img class=\"icon\" src=\"MenuIcons/").append(id).append(".png\" alt=\"\">");
        }
        sb.append("<div><b>").append(esc(it.linkName())).append("</b>");
        if (o.info1() && !it.infoText1().isBlank()) sb.append("<div class=\"small\">").append(esc(it.infoText1())).append("</div>");
        if (o.info2() && !it.infoText2().isBlank()) sb.append("<div class=\"small\">").append(esc(it.infoText2())).append("</div>");
        if (o.previews() && it.preview() != null) {
            Files.write(dir.resolve("MenuPreviews").resolve(id + ".png"), it.preview());
            sb.append("<div><img class=\"preview\" src=\"MenuPreviews/").append(id).append(".png\" alt=\"\"></div>");
        }
        if (o.description() && !it.description().isBlank()) sb.append("<p>").append(lines(it.description())).append("</p>");
        if (o.info() && !it.info().isBlank()) sb.append("<p class=\"small\">").append(lines(it.info())).append("</p>");
        if (o.tgi()) sb.append("<div class=\"tgi\">").append(it.kind().luaName).append(" ").append(it.exemplarTgi()).append("</div>");
        sb.append("</div></div>\n");
    }

    static String esc(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }

    private static String lines(String s) {
        return String.join("<br>", List.of(esc(s).split("\r?\n")));
    }
}
